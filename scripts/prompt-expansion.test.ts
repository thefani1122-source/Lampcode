/**
 * Prompt expansion must never change, extend or reinterpret the user's text.
 * Derived task/runtime metadata is carried separately by PromptBuilder.
 */
import { readFileSync } from "node:fs";
import { expandUserPrompt } from "../src/agents/prompt-builder.js";

let failures = 0;
function check(name: string, condition: boolean): void {
  if (!condition) {
    failures++;
    console.error("FAIL: " + name);
  } else {
    console.log("PASS: " + name);
  }
}

const prompts = [
  "  Build a habit tracker using my existing PostgreSQL database. Do not add social features.  ",
  "Explain this function; do not edit any files.\nKeep the answer short.  ",
  "fix only the login validation bug; do not redesign the form",
  "   ",
];
for (const prompt of prompts) {
  check("prompt is returned byte-for-byte unchanged: " + JSON.stringify(prompt), expandUserPrompt(prompt) === prompt);
}

const source = readFileSync("src/agents/prompt-builder.ts", "utf8");
check("prompt builder does not append a universal hidden preview-data contract", !source.includes("UNIVERSAL_PREVIEW_DATA_CONTRACT"));
check("prompt builder has no legacy product-feature prompt expansion", !source.includes("Build the complete, fully-functional version:"));
check("original request is explicitly marked verbatim and authoritative", source.includes("Original user request (verbatim — authoritative)"));
check("generated task descriptions are labelled non-user-authored", source.includes("Runtime and task context (generated by LampCode; not user-authored)"));
check("generated requirements are explicitly lower-priority hints", source.includes("They must not add features or override explicit user choices."));
const routeSource = readFileSync("src/server/routes/build.ts", "utf8");
check("full-stack prefix retains the unchanged original request", routeSource.includes("return `${prefix}\\n${expandUserPrompt(prompt)}`;"));
check("query request is passed verbatim without a second tool catalogue", routeSource.includes("const queryTaskDescription = prompt;"));

if (failures > 0) {
  console.error(`\n${failures} prompt-fidelity regression test(s) failed.`);
  process.exit(1);
}
console.log("\nAll prompt-fidelity and no-expansion tests passed.");
