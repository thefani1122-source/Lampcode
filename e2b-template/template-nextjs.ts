const LAYOUT_TSX = `import type { Metadata } from 'next'
import './globals.css'
export const metadata: Metadata = { title: 'App', description: 'Generated by Lampcode' }
export default function RootLayout({ children }: { children: React.ReactNode }) {
  return <html lang="en"><body>{children}</body></html>
}`

const PAGE_TSX = `export default function Page() {
  return <main style={{ padding: 24, fontFamily: 'system-ui' }}>Loading…</main>
}`

const GLOBALS_CSS = `* { box-sizing: border-box; }
body { margin: 0; font-family: system-ui, -apple-system, sans-serif; }`

const writeFile = (path: string, body: string): string => {
  const b64 = Buffer.from(body, 'utf8').toString('base64')
  return `RUN mkdir -p "$(dirname ${path})" && echo '${b64}' | base64 -d > ${path}`
}

const dockerfile = [
  'FROM node:20-slim',
  'RUN apt-get update && apt-get install -y git curl ca-certificates && rm -rf /var/lib/apt/lists/*',
  'RUN npm install -g typescript',
  'WORKDIR /home/user/app',
  writeFile('/home/user/app/package.json', PKG_JSON),
  writeFile('/home/user/app/next.config.ts', NEXT_CONFIG),
  writeFile('/home/user/app/tsconfig.json', TSCONFIG),
  writeFile('/home/user/app/app/layout.tsx', LAYOUT_TSX),
  writeFile('/home/user/app/app/page.tsx', PAGE_TSX),
  writeFile('/home/user/app/app/globals.css', GLOBALS_CSS),
  'RUN npm install',
  // Pre-warm production build cache (SWC artifacts shared with dev mode)
  'RUN npx next build || true',
  // Warm next dev cache: start server, wait for boot, hit / to trigger route compilation, then kill.
  'RUN npx next dev --port 3000 --hostname 0.0.0.0 & PID=$!; sleep 8; curl -sf http://localhost:3000/ > /dev/null || true; sleep 5; kill $PID 2>/dev/null; wait $PID 2>/dev/null || true',
].join('\n')

export const template = Template().fromDockerfile(dockerfile)
